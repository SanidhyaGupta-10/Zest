import express from 'express';
import { chatController, taskController, getChats, getChatMessages, ingestDocumentController, getUserSummaries, getUserNotes, getUserQuestions } from './ai.controller';
import { requireAuth } from '@clerk/express';
import { rateLimit } from '../../middleware/rateLimit';
import { attachUser } from '../../middleware/auth';

const router = express.Router();

// Ensure all AI routes are protected and have req.user populated
router.use(requireAuth(), attachUser);

/**
 * Chat / Ask AI (Hybrid RAG)
 * POST /api/ai/chat
 */
router.post(
    "/chat",
    rateLimit,
    chatController
);

/**
 * Unified AI Tasks (Questions, Summary, Notes)
 * POST /api/ai/tasks
 */
router.post(
    "/tasks",
    rateLimit,
    taskController
);

/**
 * Chat History
 */
router.get(
    "/chats",
    getChats
);

/**
 * What this API does?
 * => Returns all the chats created by the user
 * GET /api/ai/chats
 */

router.get(
    "/chats/:chatId",
    getChatMessages
);

/**
 * History Routes - User's Generated Content
 */
router.get(
    "/history/summaries",
    getUserSummaries
);

/**
 * What this API does?
 * => Returns all the notes generated by the user
 * GET /api/ai/history/notes
 */

router.get(
    "/history/notes",
    getUserNotes
);

/**
 * What this API does?
 * => Returns all the questions generated by the user
 * GET /api/ai/history/questions
 */

router.get(
    "/history/questions",
    getUserQuestions
);

/**
 * What this API does?
 * => Takes a document content and chunks it into smaller pieces, then stores the embeddings in the database for RAG (Retrieval Augmented Generation)
 * Document Ingestion
 * POST /api/ai/ingest
 */
router.post(
    "/ingest",
    rateLimit,
    ingestDocumentController
);

export default router;